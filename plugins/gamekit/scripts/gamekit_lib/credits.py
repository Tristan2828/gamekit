"""CREDITS.md, generated from the license info in the manifest.

Published builds must credit CC-BY authors; listing CC0 ones too is good manners
and makes it easy to check where everything came from.
"""
from __future__ import annotations

from .manifest import LICENSED_SOURCES, SOURCES, Manifest

HEADER = "<!-- Generated by `gamekit credits` from assets.yaml. Edit the manifest, not this file. -->"


def render(manifest: Manifest) -> str:
    lines = [HEADER, "", f"# Credits{': ' + manifest.game if manifest.game else ''}", ""]
    by_author: dict[tuple[str, str, str], list[str]] = {}
    own: dict[str, int] = {}
    for a in manifest.assets:
        if a.status == "todo":
            continue
        if a.source in LICENSED_SOURCES or a.license:
            key = (a.license.get("author", "Unknown author"), a.license.get("name", "Unknown license"),
                   a.license.get("url", ""))
            by_author.setdefault(key, []).append(a.id)
        else:
            own[a.source] = own.get(a.source, 0) + 1

    if by_author:
        lines += ["## Third-party assets", ""]
        for (author, license_name, url), ids in sorted(by_author.items()):
            source = f" ([source]({url}))" if url else ""
            lines.append(f"- **{author}**, {license_name}{source}: {', '.join(sorted(ids))}")
        lines.append("")
    if own:
        lines += ["## Made for this game", ""]
        for source, count in sorted(own.items()):
            lines.append(f"- {count} asset{'s' if count != 1 else ''} {SOURCES.get(source, source)}")
        lines.append("")
    if not by_author and not own:
        lines += ["No finished assets yet.", ""]
    return "\n".join(lines)
